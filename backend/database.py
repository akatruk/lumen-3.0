"""Small DB-API adapter for the application's static, parameterized SQL.

SQLite remains available for offline development. Production uses PostgreSQL.
No connection URL or query parameters are logged here.
"""
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from .config import settings

WRITE_LOCK = 481920261
SCHEMA_LOCK = 481920262
WORKER_LOCK = 481920263

class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

def row_factory(cursor):
    names = [col.name for col in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))

class Database:
    def __init__(self, connection, postgres):
        self.connection = connection
        self.postgres = postgres

    def execute(self, query, params=None):
        # Application queries are static SQL; user values are always parameters.
        if self.postgres and params is not None:
            query = query.replace('?', '%s')
        return self.connection.execute(query, params) if params is not None else self.connection.execute(query)

    def lock(self):
        # Preserve the short read-check-write critical sections formerly guarded
        # by SQLite BEGIN IMMEDIATE. Never hold this lock over a network/AI call.
        if self.postgres:
            self.execute('SELECT pg_advisory_xact_lock(?)', (WRITE_LOCK,))
        else:
            self.execute('BEGIN IMMEDIATE')

    def schema_lock(self):
        if self.postgres:
            self.execute('SELECT pg_advisory_xact_lock(?)', (SCHEMA_LOCK,))

    def executescript(self, script):
        if self.postgres:
            script = script.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            script = script.replace(' REAL', ' DOUBLE PRECISION')
        for statement in script.split(';'):
            if statement.strip(): self.execute(statement)

    def columns(self, table):
        if table != 'sessions': raise ValueError('Unsupported schema inspection')
        if self.postgres:
            return {r[0] for r in self.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=?", (table,))}
        return {r[1] for r in self.execute('PRAGMA table_info(sessions)')}

def sqlite_file(url: str | None = None) -> Path | None:
    """Absolute sqlite file when DATABASE_URL is sqlite:///... Empty means the data-dir default."""
    raw = (settings.database_url if url is None else url).strip()
    if not raw:
        return None
    if not raw.lower().startswith('sqlite:'):
        return None
    rest = raw.split(':', 1)[1]
    if not rest.startswith('////'):
        raise ValueError('sqlite_url_must_be_absolute')
    path = Path(rest[3:])
    if not path.is_absolute():
        raise ValueError('sqlite_url_must_be_absolute')
    return path


def uses_postgres(url: str | None = None) -> bool:
    raw = (settings.database_url if url is None else url).strip()
    return bool(raw) and sqlite_file(raw) is None


@contextmanager
def connect():
    postgres = uses_postgres()
    if postgres:
        import psycopg
        conn = psycopg.connect(settings.database_url, row_factory=row_factory, connect_timeout=10)
    else:
        target = sqlite_file() or (settings.data_dir / 'lumen.db')
        target.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(target, timeout=30)
        conn.row_factory = sqlite3.Row
        conn.execute('PRAGMA foreign_keys=ON')
    try:
        yield Database(conn, postgres)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

@contextmanager
def worker_guard():
    """One worker across hosts; paid calls are never automatically replayed."""
    if not uses_postgres():
        yield None
        return
    import psycopg
    with psycopg.connect(settings.database_url, autocommit=True, connect_timeout=10) as conn:
        if not conn.execute('SELECT pg_try_advisory_lock(%s)', (WORKER_LOCK,)).fetchone()[0]:
            raise RuntimeError('A Lumen worker is already running')
        yield conn
